function t(k, vars){
  let s = (I18N[LANG] && I18N[LANG][k]) || I18N.zh[k] || k;
  if(vars) Object.keys(vars).forEach(v => { s = s.split('{' + v + '}').join(vars[v]); });
  return s;
}
function TI18N(k){ return t(k); }
/* 双语标签取值:{zh,en} 对象或普通字符串 */
function lb(x){ return x == null ? '' : (typeof x === 'object' ? (x[LANG] != null ? x[LANG] : x.zh) : x); }
/* 本地化数字与日期 */
function fmtNum(v, d){ return v == null ? '—' : v.toLocaleString(LANG === 'en' ? 'en-US' : 'zh-CN', { maximumFractionDigits: d ?? 1, minimumFractionDigits: 0 }); }
